import { writeFileSync } from 'node:fs'
import { cuss } from 'cuss'

const ALLOW = new Set([
  'barf', 'beanbag', 'beanbags', 'bong', 'booby', 'bung', 'carruth', 'chug', 'chugs', 'chunkies', 'chunky',
  'cocky', 'diddle', 'dipstick', 'dong', 'dope', 'eight ball', 'eight balls', 'ero', 'evl', 'fatah', 'flange',
  'forni', 'fu', 'gables', 'geez', 'geni', 'ho', 'hobo', 'hork', 'hoser', 'jeez', 'jig', 'jigger', 'jiggers',
  'jigs', 'kumquat', 'kwa', 'mams', 'muncher', 'niggle', 'niggled', 'niggles', 'niggling', 'nigglings', 'nip',
  'noonan', 'orga', 'panti', 'pom', 'poo', 'poop', 'pooper', 'pooping', 'puke', 'rearend', 'rere', 'sadis',
  'sadom', 'scallywag', 'sexed', 'sexing', 'shav', 'skwe', 'slave', 'sooty', 'spit', 'spitter', 'spunky',
  'stringer', 'sucker', 'tang', 'teste', 'thirdeye', 'threeway', 'tinker', 'tinkers', 'tortur', 'triplex',
  'turnon', 'uck', 'usama', 'vibr', 'vomit', 'wab', 'welfare', 'wetb', 'whacker', 'whash', 'whiz', 'willie',
  'wn', 'yank', 'yanks',
])

const words = Object.entries(cuss)
  .filter(([word, rating]) => rating === 2 && /^[a-z]+(?: [a-z]+)*$/.test(word) && !ALLOW.has(word))
  .map(([word]) => word)

const lines = []
let line = ''
for (const word of words) {
  const item = `'${word}',`
  if (line && line.length + item.length + 1 > 110) {
    lines.push(line)
    line = ''
  }
  line = line ? `${line} ${item}` : item
}
if (line) lines.push(line)

writeFileSync(
  new URL('../hooks/cuss-words.js', import.meta.url),
  `// Generated by scripts/cuss-words.mjs. Do not edit.\n// Words from cuss, MIT License, Copyright (c) 2016 Titus Wormer.\nexport const CUSS_WORDS = [\n${lines.map(l => `  ${l}`).join('\n')}\n]\n`,
)
